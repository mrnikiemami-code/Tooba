export type AuthoringMessages = Record<AuthoringMessageKey, string>;

/** Messages of one interface locale (default fa; the two locales are never mixed). */
export function authoringMessages(locale: AuthoringLocale): AuthoringMessages {
  return locale === "en" ? en : fa;
}

/** Safe `{name}` interpolation; an absent value never keeps the raw placeholder. */
export function authoringFormat(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_match, key: string) => {
    const value = values[key];
    return value === undefined || value === null ? "" : String(value);
  });
}
